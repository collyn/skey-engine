/// Write packed VIQR bytes from a u32: byte0 byte1 byte2 (skip 0x00).
fn push_viqr_bytes(out: &mut Vec<u8>, w: u32) {
    let b0 = (w & 0xFF) as u8;
    let b1 = ((w >> 8) & 0xFF) as u8;
    let b2 = ((w >> 16) & 0xFF) as u8;
    if b0 != 0 { out.push(b0); }
    if b1 != 0 { out.push(b1); }
    if b2 != 0 { out.push(b2); }
}

