// ── Encode / Decode ─────────────────────────────────────────────────

/// Get the output table for a single-byte charset.
fn sb_table(cs: VietCharset) -> &'static [u8] {
    match cs {
        VietCharset::TCVN3 => &TCVN3_TABLE,
        VietCharset::VPS => &VPS_TABLE,
        VietCharset::VISCII => &VISCII_TABLE,
        VietCharset::BKHCM1 => &BKHCM1_TABLE,
        VietCharset::VietwareF => &VIETWAREF_TABLE,
        VietCharset::ISC => &ISC_TABLE,
        _ => &TCVN3_TABLE,
    }
}

/// Get the output table for a double-byte charset (little-endian word).
fn db_table(cs: VietCharset) -> &'static [u16] {
    match cs {
        VietCharset::VNIWin => &VNIWIN_TABLE,
        VietCharset::BKHCM2 => &BKHCM2_TABLE,
        VietCharset::VietwareX => &VIETWAREX_TABLE,
        VietCharset::VNIMac => &VNI_MAC_TABLE,
        _ => &VNIWIN_TABLE,
    }
}

fn is_single_byte(cs: VietCharset) -> bool {
    matches!(cs, VietCharset::TCVN3 | VietCharset::VPS | VietCharset::VISCII
        | VietCharset::BKHCM1 | VietCharset::VietwareF | VietCharset::ISC)
}

fn is_double_byte(cs: VietCharset) -> bool {
    matches!(cs, VietCharset::VNIWin | VietCharset::BKHCM2
        | VietCharset::VietwareX | VietCharset::VNIMac)
}

/// Encode a UTF-8 string to target charset bytes.
pub fn encode(input: &str, charset: VietCharset) -> Vec<u8> {
    match charset {
        VietCharset::Unicode => input.as_bytes().to_vec(),
        cs if is_single_byte(cs) => {
            encode_sb(input, sb_table(cs))
        }
        cs if is_double_byte(cs) => {
            encode_db(input, db_table(cs))
        }
        VietCharset::WinCP1258 => encode_wincp(input),
        VietCharset::VIQR => encode_viqr(input),
        VietCharset::UnicodeDecomposed => encode_nfd(input),
        _ => input.as_bytes().to_vec(),
    }
}

fn encode_sb(input: &str, table: &[u8]) -> Vec<u8> {
    let map = unicode_to_index_map();
    let mut out = Vec::with_capacity(input.len());
    for ch in input.chars() {
        if let Some(&idx) = map.get(&ch) {
            out.push(table[idx]);
        } else {
            let mut buf = [0u8; 4];
            let s = ch.encode_utf8(&mut buf);
            out.extend_from_slice(s.as_bytes());
        }
    }
    out
}

fn encode_db(input: &str, table: &[u16]) -> Vec<u8> {
    let map = unicode_to_index_map();
    let mut out = Vec::with_capacity(input.len() * 2);
    for ch in input.chars() {
        if let Some(&idx) = map.get(&ch) {
            let w = table[idx];
            out.push((w & 0xFF) as u8);
            out.push((w >> 8) as u8);
        } else if ch.is_ascii() {
            out.push(ch as u8);
        } else {
            let mut buf = [0u8; 4];
            let s = ch.encode_utf8(&mut buf);
            out.extend_from_slice(s.as_bytes());
        }
    }
    out
}

fn encode_wincp(input: &str) -> Vec<u8> {
    let map = unicode_to_index_map();
    let mut out = Vec::with_capacity(input.len() * 2);
    for ch in input.chars() {
        if let Some(&idx) = map.get(&ch) {
            let w = WINCP1258_TABLE[idx];
            out.push((w & 0xFF) as u8);
            let hi = (w >> 8) as u8;
            if hi != 0 { out.push(hi); }
        } else if ch.is_ascii() {
            out.push(ch as u8);
        } else {
            let mut buf = [0u8; 4];
            let s = ch.encode_utf8(&mut buf);
            out.extend_from_slice(s.as_bytes());
        }
    }
    out
}

fn encode_viqr(input: &str) -> Vec<u8> {
    let map = unicode_to_index_map();
    let mut out = Vec::new();
    for ch in input.chars() {
        if let Some(&idx) = map.get(&ch) {
            push_viqr_bytes(&mut out, VIQR_TABLE[idx]);
        } else if ch.is_ascii() {
            out.push(ch as u8);
        } else {
            let mut buf = [0u8; 4];
            let s = ch.encode_utf8(&mut buf);
            out.extend_from_slice(s.as_bytes());
        }
    }
    out
}

fn encode_nfd(input: &str) -> Vec<u8> {
    let map = unicode_to_index_map();
    let mut out = Vec::with_capacity(input.len() * 6);
    for ch in input.chars() {
        if let Some(&idx) = map.get(&ch) {
            let w = UNICOMP_TABLE[idx];
            let base = w & 0xFFFF;
            let comb = (w >> 16) & 0xFFFF;
            // Encode base char as UTF-8
            if let Some(c) = char::from_u32(base) {
                let mut buf = [0u8; 4];
                let s = c.encode_utf8(&mut buf);
                out.extend_from_slice(s.as_bytes());
            }
            // Encode combining mark as UTF-8 (if present)
            if comb != 0 {
                if let Some(c) = char::from_u32(comb) {
                    let mut buf = [0u8; 4];
                    let s = c.encode_utf8(&mut buf);
                    out.extend_from_slice(s.as_bytes());
                }
            }
        } else {
            let mut buf = [0u8; 4];
            let s = ch.encode_utf8(&mut buf);
            out.extend_from_slice(s.as_bytes());
        }
    }
    out
}

/// Decode charset bytes to a UTF-8 string.
pub fn decode(input: &[u8], charset: VietCharset) -> String {
    match charset {
        VietCharset::Unicode => String::from_utf8_lossy(input).to_string(),
        VietCharset::WinCP1258 => {
            let _map = unicode_to_index_map();
            // Build reverse: (base_byte, combining_byte) → index
            let mut rev: HashMap<(u8, u8), usize> = HashMap::with_capacity(VN_CHAR_COUNT);
            for (i, &w) in WINCP1258_TABLE.iter().enumerate() {
                let lo = (w & 0xFF) as u8;
                let hi = (w >> 8) as u8;
                rev.insert((lo, hi), i);
            }
            let mut out = String::with_capacity(input.len());
            let mut i = 0;
            while i < input.len() {
                let lo = input[i];
                // Try 2-byte WinCP1258 pair (combining mark follows base)
                if i + 1 < input.len() {
                    let hi = input[i + 1];
                    if let Some(&idx) = rev.get(&(lo, hi)) {
                        out.push(UNICODE_TABLE[idx]);
                        i += 2;
                        continue;
                    }
                }
                // Try single-byte entry
                if let Some(&idx) = rev.get(&(lo, 0)) {
                    out.push(UNICODE_TABLE[idx]);
                } else {
                    out.push(lo as char);
                }
                i += 1;
            }
            out
        }
        VietCharset::VIQR => {
            // VIQR decode: use the engine's built-in VIQR converter
            let s = String::from_utf8_lossy(input);
            crate::engine::convert_viqr(&s)
        }
        VietCharset::TCVN3 => {
            let map = tcvn3_to_index_map();
            let mut out = String::with_capacity(input.len());
            for &b in input {
                if let Some(&idx) = map.get(&b) {
                    out.push(UNICODE_TABLE[idx]);
                } else {
                    out.push(b as char);
                }
            }
            out
        }
        VietCharset::VNIWin => {
            let map = vniwin_to_index_map();
            let mut out = String::with_capacity(input.len());
            let mut i = 0;
            while i < input.len() {
                // Try 2-byte VNI-WIN pair
                if i + 1 < input.len() {
                    let lo = input[i];
                    let hi = input[i + 1];
                    let w = lo as u16 | ((hi as u16) << 8);
                    if let Some(&idx) = map.get(&w) {
                        out.push(UNICODE_TABLE[idx]);
                        i += 2;
                        continue;
                    }
                }
                // Fallback: single byte pass-through
                out.push(input[i] as char);
                i += 1;
            }
            out
        }
        // Generic: all single-byte charsets decode the same way
        cs if is_single_byte(cs) => {
            let table = sb_table(cs);
            let mut rev: HashMap<u8, usize> = HashMap::with_capacity(VN_CHAR_COUNT);
            for (i, &b) in table.iter().enumerate() {
                rev.insert(b, i);
            }
            let mut out = String::with_capacity(input.len());
            for &b in input {
                if let Some(&idx) = rev.get(&b) {
                    out.push(UNICODE_TABLE[idx]);
                } else {
                    out.push(b as char);
                }
            }
            out
        }
        // Generic: all double-byte charsets decode the same way
        cs if is_double_byte(cs) => {
            let table = db_table(cs);
            let mut rev: HashMap<u16, usize> = HashMap::with_capacity(VN_CHAR_COUNT);
            for (i, &w) in table.iter().enumerate() {
                rev.insert(w, i);
            }
            let mut out = String::with_capacity(input.len());
            let mut i = 0;
            while i < input.len() {
                if i + 1 < input.len() {
                    let lo = input[i];
                    let hi = input[i + 1];
                    let w = lo as u16 | ((hi as u16) << 8);
                    if let Some(&idx) = rev.get(&w) {
                        out.push(UNICODE_TABLE[idx]);
                        i += 2;
                        continue;
                    }
                }
                out.push(input[i] as char);
                i += 1;
            }
            out
        }
        // NFD: pass through (decode as UTF-8)
        VietCharset::UnicodeDecomposed => String::from_utf8_lossy(input).to_string(),
        // All other variants (single-byte, double-byte) handled above via guard arms
        _ => String::from_utf8_lossy(input).to_string(),
    }
}

/// Remove tone marks from a Vietnamese UTF-8 string.
/// e.g. "tiếng Việt" → "tiêng Viêt"
pub fn remove_tone(input: &str) -> String {
    let map = unicode_to_index_map();
    let mut out = String::with_capacity(input.len());
    for ch in input.chars() {
        if let Some(&idx) = map.get(&ch) {
            let toneless_idx = NO_TONE[idx];
            out.push(UNICODE_TABLE[toneless_idx]);
        } else {
            out.push(ch);
        }
    }
    out
}

